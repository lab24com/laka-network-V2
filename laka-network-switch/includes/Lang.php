	/** Selects the language from the widget field value (Lang::AUTO, ENGLISH, SPANISH or PORTUGUESE). */
	public static function setLanguage(int $choice): void {
		self::$language = match ($choice) {
			self::ENGLISH => 'en',
			self::SPANISH => 'es',
			self::PORTUGUESE => 'pt',
			default => self::userLanguage()
		};
	}

	/** Selects the language from a code sent by the browser ('en', 'es', 'pt' or 'auto'). */
	public static function setLanguageCode(string $code): void {
		self::$language = in_array($code, ['en', 'es', 'pt'], true) ? $code : self::userLanguage();
	}

	public static function language(): string {
		return self::$language ??= self::userLanguage();
	}

	/** BCP 47 locale used by the browser for dates and numbers. */
	public static function locale(): string {
		return ['es' => 'es', 'pt' => 'pt-BR', 'en' => 'en-US'][self::language()] ?? 'en-US';
	}

	public static function t(string $text): string {
		switch (self::language()) {
			case 'es':
				return self::ES[$text] ?? $text;
			case 'pt':
				return self::PT[$text] ?? $text;
			case 'en':
				return $text;
			default:
				return function_exists('_') ? _($text) : $text;
		}
	}

	/** Dictionary passed to the browser. */
	public static function js(): array {
		$result = [];
		foreach (self::JS as $key) $result[$key] = self::t($key);
		return $result;
	}

	/** Language of the Zabbix user: 'es', 'pt', or 'auto' (English / Zabbix gettext). */
	private static function userLanguage(): string {
		$lang = '';
		if (class_exists('CWebUser') && isset(\CWebUser::$data['lang'])) $lang = (string) \CWebUser::$data['lang'];
		if (($lang === '' || $lang === 'default') && class_exists('CSettingsHelper')) {
			try {
				$lang = (string) \CSettingsHelper::get(\CSettingsHelper::DEFAULT_LANG);
			}
			catch (\Throwable $exception) {
				$lang = '';
			}
		}
		$lang = strtolower($lang);
		if (str_starts_with($lang, 'es')) return 'es';
		if (str_starts_with($lang, 'pt')) return 'pt';
		return 'auto';
	}
